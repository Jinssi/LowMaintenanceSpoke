// Builds an Iconify JSON icon pack (prefix "azure") from the official Azure Architecture Icons,
// so Mermaid diagrams can use e.g. `azure:container-apps-environments`.
//
// Usage: node build-azure-iconpack.mjs [path-to-extracted-icons-folder]
// Without an argument the official zip is downloaded from Microsoft Learn into a temp folder.
// Icons: https://learn.microsoft.com/azure/architecture/icons/ (see terms of use on that page).

import { execFileSync } from 'node:child_process';
import { existsSync, mkdtempSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SVG, IconSet, cleanupSVG, runSVGO } from '@iconify/tools';
import { readFile } from 'node:fs/promises';

const ICONS_ZIP_URL = 'https://arch-center.azureedge.net/icons/Azure_Public_Service_Icons_V24.zip';
const here = fileURLToPath(new URL('.', import.meta.url));
const outJson = join(here, 'azure-icons.json');
const outIndex = join(here, 'icon-index.md');

function listSvgs(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return listSvgs(full);
    return name.toLowerCase().endsWith('.svg') ? [full] : [];
  });
}

// "10021-icon-service-Container-Apps-Environments.svg" -> "container-apps-environments"
function iconName(file) {
  return basename(file, '.svg')
    .replace(/^\d+-icon-service-/i, '')
    .replace(/^\d+-/, '')
    .replace(/[^a-zA-Z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .toLowerCase();
}

async function downloadAndExtract() {
  const work = mkdtempSync(join(tmpdir(), 'azure-icons-'));
  const zipPath = join(work, 'icons.zip');
  console.log(`Downloading ${ICONS_ZIP_URL} ...`);
  const res = await fetch(ICONS_ZIP_URL);
  if (!res.ok) throw new Error(`Download failed: ${res.status} ${res.statusText}`);
  writeFileSync(zipPath, Buffer.from(await res.arrayBuffer()));
  const dest = join(work, 'icons');
  execFileSync(process.platform === 'win32' ? 'tar' : 'unzip', process.platform === 'win32' ? ['-xf', zipPath, '-C', work] : ['-q', zipPath, '-d', work]);
  const folder = readdirSync(work).map((n) => join(work, n)).find((p) => statSync(p).isDirectory());
  return { folder: folder ?? dest, cleanup: () => rmSync(work, { recursive: true, force: true }) };
}

const arg = process.argv[2];
const source = arg && existsSync(arg) ? { folder: arg, cleanup: () => {} } : await downloadAndExtract();

try {
  const iconSet = new IconSet({ prefix: 'azure', icons: {}, info: { name: 'Azure Architecture Icons', author: { name: 'Microsoft' }, license: { title: 'Microsoft Azure Architecture Icons terms', url: 'https://learn.microsoft.com/azure/architecture/icons/' } } });
  const index = [];
  let skipped = 0;

  for (const file of listSvgs(source.folder).sort()) {
    const name = iconName(file);
    if (!name || iconSet.exists(name)) { skipped++; continue; } // same icon appears in several categories
    try {
      const svg = new SVG(await readFile(file, 'utf8'));
      cleanupSVG(svg);
      runSVGO(svg); // also prefixes gradient/clip IDs so icons don't collide on one page
      iconSet.fromSVG(name, svg);
      const category = basename(dirname(file));
      index.push({ name, category });
    } catch (err) {
      console.warn(`Skipping ${basename(file)}: ${err.message}`);
      skipped++;
    }
  }

  writeFileSync(outJson, JSON.stringify(iconSet.export(), null, 0));

  const byCategory = Object.groupBy(index, (i) => i.category);
  const md = ['# Azure icon pack for Mermaid', '', `Generated by \`build-azure-iconpack.mjs\` from the official Azure Architecture Icons (${basename(ICONS_ZIP_URL)}).`, '', 'Use as `azure:<name>`, e.g. `service app(azure:container-apps-environments)[Apps]`.', '', `Total icons: ${index.length}`, ''];
  for (const category of Object.keys(byCategory).sort()) {
    md.push(`## ${category}`, '', byCategory[category].map((i) => `\`${i.name}\``).join(' · '), '');
  }
  writeFileSync(outIndex, md.join('\n'));
  console.log(`Wrote ${index.length} icons to ${outJson} (${skipped} duplicates/invalid skipped).`);
} finally {
  source.cleanup();
}
